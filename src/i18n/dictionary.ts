// Browser-side runtime locale detection (dev mode)
function getBrowserLocale(): Locale | null {
  if (typeof window !== "undefined") {
    try {
      const params = new URLSearchParams(window.location.search);
      const lang = params.get("lang");
      if (lang === "en" || lang === "zh") return lang;

      const cookieMatch = document.cookie.match(/user_lang=(zh|en)/);
      if (cookieMatch) return cookieMatch[1] as Locale;
    } catch { /* ignore */ }
  }
  return null;
}

// Build-time locale - determined at build time by NEXT_PUBLIC_LOCALE
export const buildLocale: Locale =
  process.env.NEXT_PUBLIC_LOCALE === "en"
    ? "en"
    : "zh";

// Helper to get a nested key with fallback
// In browser dev mode, it dynamically checks URL params for runtime locale switching
// Supports: t(key), t(key, params), t(key, locale, params)
export function t(
  key: string,
  localeOrParams?: Locale | Record<string, string | number>,
  params?: Record<string, string | number>
): string {
  const runtimeLocale = getBrowserLocale();
  const locale = typeof localeOrParams === "string" ? localeOrParams : buildLocale;
  const actualParams = typeof localeOrParams === "object" ? localeOrParams : params;
  const activeLocale = runtimeLocale || locale;
  const entry = DICTIONARY[key];
  if (!entry) {
    console.warn("[i18n] Missing key: " + key);
    return key;
  }
  let text = entry[activeLocale] || key;
  if (actualParams) {
    for (const [k, v] of Object.entries(actualParams)) {
      text = text.replace(new RegExp("\\{" + k + "\\}", "g"), String(v));
    }
  }
  return text;
}

// Create a translator bound to a specific locale (useful for Server Components with URL params)
export function createT(locale: Locale) {
  return (key: string, params?: Record<string, string | number>) => t(key, locale, params);
}

// Determine locale from URL search params at request time (Server Component usage)
export function getLocaleFromSearchParams(searchParams?: { lang?: string }): Locale {
  if (searchParams?.lang === "en" || searchParams?.lang === "zh") {
    return searchParams.lang;
  }
  return buildLocale;
}

// Returns "?lang=en" or "?lang=zh" or "" based on current URL/cookie
// Use this to append lang param to all internal links
export function getLangQuery(): string {
  const locale = getBrowserLocale();
  if (locale) return `?lang=${locale}`;
  return "";
}

// Deprecated alias kept for backward compatibility in non-page files
export const currentLocale = buildLocale;

// Returns the BCP 47 locale string for Date/Intl APIs based on runtime locale
export function getDateTimeLocale(): string {
  const locale = getBrowserLocale() || buildLocale;
  return locale === "en" ? "en-US" : "zh-CN";
}
